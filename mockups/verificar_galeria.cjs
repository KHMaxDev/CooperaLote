const fs = require('node:fs');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {chromium} = require('C:/Users/madox/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert = require('node:assert/strict');
(async () => {
  const root=__dirname;
  const candidates=[chromium.executablePath(),'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe','C:/Program Files/Google/Chrome/Application/chrome.exe'];
  const executablePath=candidates.find(p=>fs.existsSync(p));
  assert(executablePath,'Se necesita un navegador local para la comprobación visual.');
  const browser=await chromium.launch({headless:true,executablePath});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
    const errors=[]; page.on('pageerror',e=>errors.push(e.message));
    await page.goto(pathToFileURL(path.join(root,'galeria.html')).href);
    assert.equal(await page.locator('.card').count(),4,'Inicio con cuatro vistas del productor');
    await page.locator('.card .preview').first().click();
    assert(await page.locator('dialog').evaluate(el=>el.open));
    await page.getByRole('button',{name:'Imagen siguiente',exact:true}).click();
    assert.match(await page.locator('#dialogTitle').innerText(),/P02/);
    await page.getByRole('button',{name:'Tamaño real',exact:true}).click();
    assert(await page.locator('#viewer').evaluate(el=>el.classList.contains('actual')));
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('dialog').evaluate(el=>el.open),false);
    assert(await page.locator('.card .preview').first().evaluate(el=>el===document.activeElement),'Restaura foco');
    await page.locator('[data-route="Ventas"]').click();
    assert.equal(await page.locator('.card').count(),8);
    await page.locator('#state').selectOption('situations');
    assert.equal(await page.locator('.card').count(),5);
    await page.locator('#search').fill('importe');
    assert.equal(await page.locator('.card').count(),1);
    await page.locator('#search').fill('sin-coincidencia-xyz');
    assert(await page.locator('#empty').isVisible());
    await page.getByRole('button',{name:'Ver todas las imágenes',exact:true}).click();
    assert.equal(await page.locator('.card').count(),50);
    await page.locator('#reset').click();
    await page.locator('.card img').first().evaluate(img=>img.decode());
    fs.mkdirSync(path.join(root,'revision'),{recursive:true});
    await page.screenshot({path:path.join(root,'revision','galeria-escritorio.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(root,'revision','galeria-movil.png'),fullPage:true});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Sin desbordamiento móvil');
    await page.locator('.card .preview').first().click();
    assert(await page.getByRole('button',{name:'Cerrar ✕',exact:true}).isVisible());
    await page.getByRole('button',{name:'Cerrar ✕',exact:true}).click();
    assert.deepEqual(errors,[]);
    const selected=JSON.parse(fs.readFileSync(path.join(root,'indice-v2.json'),'utf8')).screens;
    const missing=selected.filter(s=>!fs.existsSync(path.join(root,s.file))).map(s=>s.file);
    const report={selected:selected.length,browserChecks:'Correctos: perfiles, filtros, búsqueda, vacío, ampliación, zoom, Escape, foco y ancho móvil',missing,jsErrors:errors};
    fs.writeFileSync(path.join(root,'revision','verificacion.json'),JSON.stringify(report,null,2)+'\n');
    console.log(JSON.stringify(report));
    if(missing.length)process.exitCode=2;
  } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
